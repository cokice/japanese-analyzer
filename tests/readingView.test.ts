import assert from 'node:assert/strict';
import { getViewSelection, initialReadingView, readingViewReducer } from '../app/lib/readingView';

let view = readingViewReducer(initialReadingView, { type: 'analyze' });
assert.equal(view.mode, 'analyzing');
view = readingViewReducer(view, { type: 'settled', hasTokens: true });
assert.equal(view.mode, 'reading');
view = readingViewReducer(view, { type: 'word', index: 2 });
assert.deepEqual(getViewSelection(view), { selectedIndex: 2, selectedRange: null, pickAnchor: null });
view = readingViewReducer(view, { type: 'pick', anchor: 2 });
assert.deepEqual(getViewSelection(view), { selectedIndex: 2, selectedRange: null, pickAnchor: 2 });
view = readingViewReducer(view, { type: 'range', range: { start: 2, end: 4 } });
assert.deepEqual(getViewSelection(view), { selectedIndex: null, selectedRange: { start: 2, end: 4 }, pickAnchor: null });
view = readingViewReducer(view, { type: 'clearSelection' });
view = readingViewReducer(view, { type: 'pick', anchor: 4 });
assert.deepEqual(getViewSelection(view), { selectedIndex: null, selectedRange: null, pickAnchor: 4 });
view = readingViewReducer(view, { type: 'pick', anchor: null });
assert.equal(view.selection.kind, 'none');
view = readingViewReducer(view, { type: 'analyze' });
view = readingViewReducer(view, { type: 'edit' });
view = readingViewReducer(view, { type: 'settled', hasTokens: true });
assert.equal(view.mode, 'editing', 'Finishing a request must not collapse an editor the user opened');
view = readingViewReducer(view, { type: 'read' });
assert.equal(view.mode, 'reading');
view = readingViewReducer(view, { type: 'analyze' });
view = readingViewReducer(view, { type: 'settled', hasTokens: false, error: true });
assert.equal(view.mode, 'editing');
assert.deepEqual(readingViewReducer(view, { type: 'home' }), initialReadingView);
assert.equal(readingViewReducer(initialReadingView, { type: 'settled', hasTokens: false }).mode, 'home');
